// Прави data/geo/coldwar.json за „Студената война“ (9.3.2): ГДР, Западен Берлин и линията на „желязната завеса“.
// Употреба: node tools/make-coldwar-geo.mjs
//
// ВАЖНО: това е опростена схема, начертана за курса; не е точна карта.
// Бреговете на ГДР и границата по Одер и Ниса са взети от днешната граница на Германия в data/geo/europe.json
// (Natural Earth, обществено достояние). Вътрешногерманската граница, Западен Берлин и „желязната завеса“
// са начертани на ръка по общоизвестни очертания, с точност около 10–30 км.
import { readFileSync, writeFileSync } from 'node:fs';

const eu = JSON.parse(readFileSync(new URL('../data/geo/europe.json', import.meta.url), 'utf8'));
const deRings = eu.countries.find((c) => c.id === '276').rings;
const de = deRings[0];
// Островите Рюген и Узедом (средата им е на изток от 12,5°) също са в ГДР.
const islands = deRings.slice(1).filter((r) => r.reduce((s, p) => s + p[0], 0) / r.length > 12.5);
const idx = (lon, lat) => de.findIndex(([x, y]) => x === lon && y === lat);
// От Балтийско море при Любек (Привал) на изток по брега, после по Одер и Ниса до Чехословакия
// и на запад по чехословашката граница до тройната точка при Хоф.
const a = idx(10.917, 53.996), b = idx(12.357, 50.274);
if (a < 0 || b < 0 || b < a) throw new Error('Не намирам опорните точки в границата на Германия');
const eastPart = de.slice(a, b + 1);

// Вътрешногерманската граница от юг (при Хоф) на север (до Балтийско море) — на ръка, приблизително.
const inner = [
  [12.1, 50.32], [11.92, 50.42], [11.62, 50.4], [11.45, 50.5], [11.26, 50.4], [10.95, 50.38], [10.72, 50.34],
  [10.45, 50.4], [10.12, 50.55], [10.04, 50.68], [9.93, 50.76], [10.06, 50.9], [10.2, 51.0], [10.0, 51.12],
  [9.95, 51.26], [10.05, 51.38], [10.3, 51.5], [10.45, 51.6], [10.6, 51.7], [10.75, 51.93], [10.98, 52.07],
  [11.05, 52.23], [10.97, 52.4], [10.93, 52.55], [10.82, 52.72], [11.0, 52.88], [11.3, 52.97], [11.55, 53.04],
  [11.25, 53.13], [10.95, 53.22], [10.75, 53.33], [10.6, 53.38], [10.7, 53.5], [10.78, 53.65], [10.84, 53.82],
  [10.9, 53.95],
];
const gdr = [...eastPart, ...inner];

// Западен Берлин — приблизително очертание.
const wberlin = [
  [13.09, 52.42], [13.12, 52.52], [13.15, 52.6], [13.28, 52.66], [13.34, 52.63], [13.4, 52.56], [13.37, 52.52],
  [13.42, 52.5], [13.46, 52.46], [13.45, 52.4], [13.36, 52.37], [13.24, 52.38], [13.15, 52.38],
];

// „Желязната завеса“ от Балтийско море до Черно море (след 1948 г.; без Албания): вътрешногерманската граница,
// границите на Чехословакия и Унгария с Австрия, на Унгария, Румъния и България с Югославия и на България
// с Гърция и Турция.
const curtain = [
  ...inner.slice().reverse(),
  [12.55, 49.9], [12.45, 49.7], [12.75, 49.37], [13.15, 49.15], [13.4, 48.98], [13.8, 48.77],
  [14.3, 48.56], [14.7, 48.6], [15.0, 49.0], [15.6, 48.85], [16.2, 48.75], [16.9, 48.62], [17.0, 48.15],
  [17.1, 48.02], [16.95, 47.7], [16.6, 47.45], [16.45, 47.0], [16.1, 46.86],
  [16.6, 46.48], [17.3, 46.0], [18.0, 45.8], [18.9, 45.93], [19.6, 46.17], [20.26, 46.11],
  [20.8, 45.75], [21.4, 45.2], [21.6, 44.75], [22.45, 44.5], [22.7, 44.22],
  [22.55, 43.9], [22.95, 43.4], [22.5, 43.0], [22.45, 42.5], [22.37, 42.32], [22.8, 41.9], [22.95, 41.34],
  [23.6, 41.4], [24.3, 41.55], [25.1, 41.35], [26.1, 41.72], [26.6, 41.93], [27.3, 42.07], [28.0, 41.98],
];

const r3 = (ring) => ring.map(([x, y]) => [+x.toFixed(3), +y.toFixed(3)]);
writeFileSync(new URL('../data/geo/coldwar.json', import.meta.url), JSON.stringify({
  source: 'опростена схема, начертана за курса; не е точна карта. Бреговете и границата по Одер и Ниса са от Natural Earth 1:50m (обществено достояние); вътрешногерманската граница, Западен Берлин и „желязната завеса“ са начертани на ръка по общоизвестни очертания (tools/make-coldwar-geo.mjs).',
  label: 'Приблизителни граници',
  regions: [
    { id: 'gdr', name: 'ГДР', anchor: [12.4, 52.0], polygons: [[r3(gdr)], ...islands.map((r) => [r3(r)])] },
    { id: 'wberlin', name: 'Западен Берлин', anchor: [13.25, 52.5], polygons: [[r3(wberlin)]] },
  ],
  curtain: r3(curtain),
}));
console.log('ГДР:', gdr.length, 'точки; завеса:', curtain.length, 'точки');
